# List : A list is an array in python that can be used to store multiple values, objects, strings or numbers

numList = [1,2,3]
print(numList)

strList = ['Asad','Abdul','Ali']
print(strList)

mixedList = [1, 'Asad', 3.14, True]
print(mixedList)

objList = [1, 'Asad', 3.14, True, [1,2,3], {'name': 'Asad', 'age': 20}]
print(objList)

